#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
build_towns.py — يبني قوائم كل القرى دفعة واحدة.

الاستعمال:
    python3 build_towns.py source/                 # كل ملفات PDF داخل مجلد source
    python3 build_towns.py source/ --primary "بر الياس"

المخرجات (بدون مفتاح — نسخة مفتوحة للتجربة المحلية فقط):
    data.js             ← البلدة الأساسية (بر الياس)
    towns/<id>.js       ← ملف لكل قرية إضافية، بيتحمّل فقط لما يلزم
    towns.js            ← فهرس القرى (الاسم، العدد، مسار الملف)

المخرجات مع --key (النسخة المحمية — هيدي اللي بتنرفع على الموقع):
    python3 build_towns.py source/ --key <64 حرف hex>      # أو من متغيّر البيئة VOTERS_KEY
    data.enc / towns.enc / towns/<id>.enc
    كل ملف = "FAMV" + byte نسخة (1) + IV (12 byte) + AES-256-GCM(gzip(JSON))
    الصفحة بتفكّ التشفير بالمتصفح بعد الدخول بالإيميل وكلمة السر؛ المفتاح محفوظ بـ Firestore (config/key).
    لما بيكون في مفتاح ما بينكتب ولا ملف مفتوح (.js) أبداً.

لإضافة قرية: حطّ ملف الـ PDF الرسمي داخل مجلد source وشغّل السكربت (أو ارفعه على
GitHub والـ Action بيشتغل لحاله). كل شي بيتولّد تلقائياً — ما في شي بيتكتب بالإيد.
"""
import os, re, sys, json, glob, argparse, subprocess, gzip

MAGIC = b'FAMV'
FORMAT_VERSION = 1

def parse_key(hexkey):
    """مفتاح AES-256 بصيغة hex (64 حرف) -> 32 byte. بيرفض أي شي غير هيك بوضوح."""
    k = (hexkey or '').strip().lower()
    if not re.fullmatch(r'[0-9a-f]{64}', k):
        sys.exit('المفتاح لازم يكون 64 حرف hex (32 byte). ولّدو من صفحة admin.html → "مفتاح البيانات".')
    return bytes.fromhex(k)

def encrypt_blob(key, obj):
    """JSON -> gzip -> AES-256-GCM. نفس الصيغة اللي بتفكّها الصفحة بالـ Web Crypto."""
    try:
        from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    except ImportError:
        sys.exit('لازم مكتبة cryptography:  pip install cryptography')
    plain = gzip.compress(json.dumps(obj, ensure_ascii=False, separators=(',', ':')).encode('utf-8'), compresslevel=9, mtime=0)
    iv = os.urandom(12)
    return MAGIC + bytes([FORMAT_VERSION]) + iv + AESGCM(key).encrypt(iv, plain, None)

def decrypt_blob(key, blob):
    """للتأكد/التجربة فقط (عكس encrypt_blob)."""
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM
    if blob[:4] != MAGIC or blob[4] != FORMAT_VERSION:
        raise ValueError('not a FAMV file')
    return json.loads(gzip.decompress(AESGCM(key).decrypt(blob[5:17], blob[17:], None)).decode('utf-8'))

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from build_voters import parse_pdf, build   # نفس محرّك القراءة

# نقحرة بسيطة لتوليد اسم ملف لاتيني ثابت لكل قرية (ما بيتغيّر مع إضافة قرى جديدة)
TR = {'ا':'a','أ':'a','إ':'i','آ':'a','ب':'b','ت':'t','ث':'th','ج':'j','ح':'h','خ':'kh','د':'d','ذ':'th',
      'ر':'r','ز':'z','س':'s','ش':'sh','ص':'s','ض':'d','ط':'t','ظ':'z','ع':'a','غ':'gh','ف':'f','ق':'q',
      'ك':'k','ل':'l','م':'m','ن':'n','ه':'h','ة':'a','و':'w','ي':'y','ى':'a','ئ':'y','ؤ':'w','ء':'', ' ':'-'}

def slug(name, used):
    s = ''.join(TR.get(ch, '') for ch in name).strip('-')
    s = re.sub(r'-{2,}', '-', s) or 'town'
    base, i = s, 2
    while s in used:
        s = base + '-' + str(i); i += 1
    used.add(s)
    return s

def pages_of(pdf):
    try:
        out = subprocess.run(['pdfinfo', pdf], capture_output=True, text=True).stdout
        return int(re.search(r'Pages:\s+(\d+)', out).group(1))
    except Exception:
        return 0

if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('src', nargs='?', default='source')
    ap.add_argument('--primary', default='بر الياس')
    ap.add_argument('--out', default='.')
    ap.add_argument('--key', default=os.environ.get('VOTERS_KEY', ''),
                    help='مفتاح AES-256 بصيغة hex (64 حرف). مع المفتاح بتطلع ملفات .enc مشفّرة بدل .js')
    a = ap.parse_args()
    key = parse_key(a.key) if a.key else None
    ext = '.enc' if key else '.js'

    pdfs = sorted(glob.glob(os.path.join(a.src, '*.pdf')) + glob.glob(os.path.join(a.src, '*.PDF')))
    if not pdfs:
        print('ما في ملفات PDF داخل ' + a.src); sys.exit(1)

    os.makedirs(os.path.join(a.out, 'towns'), exist_ok=True)
    used, index, primary_done = set(), [], False

    def write_town(path, tid, town, meta, rows_json, is_primary):
        """بيكتب ملف قرية: مشفّر (.enc) إذا في مفتاح، وإلا .js مفتوح للتجربة المحلية."""
        if key:
            obj = {'id': tid, 'name': town, 'meta': meta, 'rows': json.loads(rows_json)}
            open(path, 'wb').write(encrypt_blob(key, obj))
        elif is_primary:
            open(path, 'w', encoding='utf-8').write(
                '// قوائم الناخبين – ' + town + ' – ' + meta['edition'] + '\n'
                '// generated by build_voters.py from the official DGCS PDF\n'
                'window.VOTERS_META = ' + json.dumps(meta, ensure_ascii=False) + ';\n'
                'window.VOTERS = ' + rows_json + ';\n')
        else:
            open(path, 'w', encoding='utf-8').write(
                '// ' + town + ' – ' + meta['edition'] + '\n'
                'window.addTown({"id":' + json.dumps(tid) + ',"name":' + json.dumps(town, ensure_ascii=False) +
                ',"meta":' + json.dumps(meta, ensure_ascii=False) + ',"rows":' + rows_json + '});\n')

    for pdf in pdfs:
        recs, kind, year, place = parse_pdf(pdf)
        if not recs:
            print('تخطّينا (ما في أسماء): ' + os.path.basename(pdf)); continue
        town = place.get('town') or os.path.splitext(os.path.basename(pdf))[0].replace('_', ' ')
        tid = slug(town, used)
        f = sum(1 for r in recs if r['sex'] == 0)
        is_primary = (not primary_done) and (town == a.primary or len(pdfs) == 1)

        js = build(recs, kind, year, town, pages_of(pdf), place, tid)
        meta = json.loads(js.split('window.VOTERS_META = ')[1].split(';\nwindow.VOTERS')[0])
        rows_json = js.split('window.VOTERS = ')[1].rstrip().rstrip(';')
        entry = {'id': tid, 'name': town, 'count': len(recs), 'females': f, 'males': len(recs)-f, 'edition': meta['edition']}
        if is_primary:
            primary_done = True
            path = os.path.join(a.out, 'data' + ext)
            entry['primary'] = True
        else:
            path = os.path.join(a.out, 'towns', tid + ext)
            entry['file'] = 'towns/' + tid + ext
        index.append(entry)
        write_town(path, tid, town, meta, rows_json, is_primary)
        print('%-14s %-10s %6d ناخب (%d إناث / %d ذكور) -> %s (%d KB)' %
              (town, '(أساسية)' if is_primary else '', len(recs), f, len(recs)-f, os.path.relpath(path, a.out), os.path.getsize(path)//1024))

    index.sort(key=lambda t: (not t.get('primary'), -t['count']))
    primary_id = next((t['id'] for t in index if t.get('primary')), index[0]['id'] if index else '')
    if key:
        open(os.path.join(a.out, 'towns.enc'), 'wb').write(encrypt_blob(key, {'towns': index, 'primary': primary_id}))
        print('towns.enc: ' + str(len(index)) + ' قرية، المجموع ' + str(sum(t['count'] for t in index)) + ' ناخب — كل الملفات مشفّرة (AES-256-GCM)')
    else:
        open(os.path.join(a.out, 'towns.js'), 'w', encoding='utf-8').write(
            '// فهرس القرى — مولّد تلقائياً من build_towns.py\n'
            'window.VOTERS_TOWNS = ' + json.dumps(index, ensure_ascii=False, indent=1) + ';\n')
        print('towns.js: ' + str(len(index)) + ' قرية، المجموع ' + str(sum(t['count'] for t in index)) + ' ناخب — ملفات مفتوحة (بدون --key)')
